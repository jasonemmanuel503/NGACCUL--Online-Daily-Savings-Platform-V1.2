export function t(key: string, lang: SupportedLanguages, portal?: 'client' | 'agent' | 'admin' | 'pdg'): string {
  if (typeof key !== 'string') return '';
  const isClient = portal === 'client';
  const val = T[lang]?.[key];
  if (lang === 'ff') {
    if (isClient) {
      return val || T.en[key] || key;
    } else {
      // fallback logic for ff on non-client portals: ff -> fr -> en
      return val || T.fr[key] || T.en[key] || key;
    }
  }
  return val || T.en[key] || key;
}
